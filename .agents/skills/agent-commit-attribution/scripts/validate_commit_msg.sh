#!/usr/bin/env bash
# ==============================================================================
# WeMi Light Control — Commit Message & Description Attribution Validator
# ==============================================================================
# Validates that a Git commit message contains:
#   1. A non-empty subject line
#   2. A non-empty commit description body (no bare 1-line commits)
#   3. Explicit agent attribution ("Agent: <Canonical Agent Name> (<role_id>)")
#      in the commit description body.
#
# Usage:
#   bash .agents/skills/agent-commit-attribution/scripts/validate_commit_msg.sh <commit-msg-file>
#   bash .agents/skills/agent-commit-attribution/scripts/validate_commit_msg.sh --install-hook
# ==============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../../.." && pwd)"

if [[ "${1:-}" == "--install-hook" ]]; then
  HOOK_PATH="${REPO_ROOT}/.git/hooks/commit-msg"
  mkdir -p "$(dirname "${HOOK_PATH}")"
  cat > "${HOOK_PATH}" <<'HOOKEOF'
#!/usr/bin/env bash
set -euo pipefail
REPO_ROOT="$(git rev-parse --show-toplevel)"
VALIDATOR="${REPO_ROOT}/.agents/skills/agent-commit-attribution/scripts/validate_commit_msg.sh"
if [[ -f "${VALIDATOR}" ]]; then
  exec bash "${VALIDATOR}" "$1"
fi
HOOKEOF
  chmod +x "${HOOK_PATH}"
  echo "[agent-commit-attribution] Installed Git commit-msg hook at ${HOOK_PATH}"
  exit 0
fi

MSG_FILE="${1:-}"
if [[ -z "${MSG_FILE}" || ! -r "${MSG_FILE}" ]]; then
  echo "Usage: $0 <commit-msg-file> | --install-hook" >&2
  exit 2
fi

RAW_MSG="$(cat "${MSG_FILE}")"
# Strip comment lines starting with '#'
CLEAN_MSG="$(printf '%s\n' "${RAW_MSG}" | grep -v '^[[:space:]]*#' || true)"
SUBJECT_LINE="$(printf '%s\n' "${CLEAN_MSG}" | sed -n '1p' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"

# Allow automatic Git mergecommits if ever generated by git merge
if [[ "${SUBJECT_LINE}" =~ ^Merge\ (branch|remote-tracking\ branch|pull\ request)\  ]]; then
  exit 0
fi

BODY_TEXT="$(printf '%s\n' "${CLEAN_MSG}" | tail -n +2 | sed '/^[[:space:]]*$/d' || true)"

ERRORS=()

if [[ -z "${SUBJECT_LINE}" ]]; then
  ERRORS+=("Commit subject line (line 1) is empty.")
fi

if [[ -z "${BODY_TEXT}" ]]; then
  ERRORS+=("Commit description body is missing (bare one-line commits are not allowed).")
fi

if ! printf '%s\n' "${BODY_TEXT}" | grep -Eq '^Agent:[[:space:]]+.+Agent([[:space:]]*\([a-z0-9_]+\))?[[:space:]]*$'; then
  ERRORS+=("Commit description must include an 'Agent: <Canonical Agent Name> (<role_id>)' line.")
fi

if (( ${#ERRORS[@]} > 0 )); then
  echo "==============================================================================" >&2
  echo "[agent-commit-attribution] COMMIT REJECTED: Missing agent name in commit description" >&2
  echo "------------------------------------------------------------------------------" >&2
  for err in "${ERRORS[@]}"; do
    echo "  - ${err}" >&2
  done
  echo "" >&2
  echo "Required format:" >&2
  echo "  <type>(<scope>): <concise summary> [<Short Agent Name>]" >&2
  echo "" >&2
  echo "  <1-4 sentence commit description explaining what changed and why.>" >&2
  echo "" >&2
  echo "  Agent: <Canonical Agent Name> (<role_id>)" >&2
  echo "" >&2
  echo "Canonical Agent Names:" >&2
  echo "  - Google AI Studio Agent (ai_studio_ux_cuj)" >&2
  echo "  - Antigravity Device Discovery & Room Grouping Agent (discovery_and_grouping)" >&2
  echo "  - Antigravity Telemetry & Debugging Agent (telemetry_and_debugging)" >&2
  echo "  - Antigravity Code Quality & E2E Testing Agent (code_quality_and_testing)" >&2
  echo "  - Antigravity License & Brand Governance Agent (license_governance)" >&2
  echo "==============================================================================" >&2
  exit 1
fi

exit 0
